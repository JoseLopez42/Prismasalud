    <script>
        const formEspecialidad = document.getElementById('form-especialidad');
        const botonGuardarEspecialidad = document.getElementById('boton-guardar-especialidad');
        const textoBotonEspecialidad = document.getElementById('texto-boton-especialidad');

        formEspecialidad.addEventListener('submit', function (evento) {
            const camposInvalidos = Array.from(formEspecialidad.querySelectorAll('.campo-form'))
                .filter(campo => !campo.checkValidity());

            if (camposInvalidos.length > 0) {
                evento.preventDefault();
                camposInvalidos.forEach(campo => {
                    campo.classList.add('campo-invalido');
                    campo.addEventListener('animationend', () => campo.classList.remove('campo-invalido'), { once: true });
                });
                camposInvalidos[0].focus();
                return;
            }

            botonGuardarEspecialidad.disabled = true;
            textoBotonEspecialidad.innerHTML = '<span class="spinner"></span> Guardando...';
        });
    </script>

